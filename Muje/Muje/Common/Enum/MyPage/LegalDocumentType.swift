import Foundation

/// 약관 동의에 대한 Type 열거형입니다.
/// - termsOfService: 서비스 이용약관
/// - privacyPolicy: 개인정보 처리방침
enum LegalDocumentType {
    case termsOfService
    case privacyPolicy


    var title: String {
        switch self {
        case .termsOfService: return "서비스 이용약관"
        case .privacyPolicy:  return "개인정보 처리방침"
        }
    }
    
    
    var content: String {
        switch self {
        case .termsOfService:
            """
            제1조 (목적) 이 약관은 파핏 (이하 ‘서비스 제공자’ 라고 함)이 제공하는 서비스(이하 “서비스”라 합니다)의 이용에 대한 서비스 제공자와 서비스 이용자의 권리ㆍ의무 및 책임사항, 기타 필요한 사항을 규정함을 목적으로 합니다.
             
            제2조 (용어의 정의)
            ① 이 약관에서 사용하는 용어의 정의는 다음과 같습니다.
             1. “서비스 제공자”라 함은 서비스를 제공하는 사업자를 의미합니다.
             2. “회원”이란 이 약관에 따라 이용계약을 체결하고, 서비스 제공자가 제공하는 서비스를 이용하는 자를 의미합니다.
