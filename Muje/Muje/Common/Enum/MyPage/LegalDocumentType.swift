            ② 서비스 제공자는 가입신청자의 신청에 대하여 승낙함을 원칙으로 합니다. 다만, 서비스 제공자는 다음 각 호의 어느 하나에 해당하는 이용 신청에 대해서는 승낙을 거절할 수 있습니다.
             1. 이용신청서 내용을 허위로 기재하거나 이용신청 요건을 충족하지 못한 경우
             2. 서비스 제공자가 서비스를 제공하지 않은 국가에서 비정상적이거나 우회적인 방법을 통해 서비스를 이용하는 경우
             3. 「정보통신망이용촉진 및 정보보호 등에 관한 법률」등 관련 법령에서 금지하는 행위를 할 목적으로 신청 하는 경우
             4. 사회의 안녕과 질서 또는 미풍양속을 저해할 목적으로 신청한 경우
             5. 부정한 용도로 서비스를 이용하고자 하는 경우
             6. 영리를 추구할 목적으로 서비스를 이용하고자 하는 경우
