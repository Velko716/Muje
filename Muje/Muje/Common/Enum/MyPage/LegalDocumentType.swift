            제4장 서비스 이용 및 이용제한
             
            제8조 (서비스의 제공)
            ① 서비스 제공자는 제4조의 규정에 따라 이용계약이 완료된 회원에게 그 즉시 서비스를 이용할 수 있도록 합니다. 다만, 일부 서비스의 경우 서비스 제공자의 필요에 따라 지정된 일자부터 서비스를 개시할 수 있습니다.
            ② 서비스 제공자는 회원에게 서비스를 제공할 때 이 약관에 정하고 있는 서비스를 포함하여 기타 부가적인 서비스를 함께 제공할 수 있습니다.
            ③ 서비스 제공자는 다음과 같은 서비스를 제공합니다.
              1. 회원의 단체의 모집에 관한 게시물을 올릴수 있는 커뮤니티 공간
              2. 모집자와 지원자간의 1:1쪽지 기능
              3. 모집자와 지원자간의 캘린더를 통한 일정관리 기능
              4. 모집자의 지원자 관리 기능 (불ㆍ합여부 처리 등)
              5. 회원이 작성한 게시글 또는 지원서 관리 기능
            ④ 서비스 제공자는 회원간에 이루어지는 채팅 내용을 저장․보관할 수 있으며 이 정보는 서비스 제공자만이 보유합니다. 서비스 제공자는 회원간의 분쟁 조정, 민원 처리 또는 질서의 유지를 위한 경우에 한하여, 제3자는 법령에 따라 권한이 부여된 경우에 한하여 이 정보를 열람할 수 있습니다.
